// 차단 시나리오는 e2e 백엔드의 `GuardrailBlocked` 직접 던지기(흉내)로 UI 계약(사유 분류만 보임, 입력 원문 비표시)만 검증한다. UI 계약 검증이며 실제 Guardrail·모델 동작 검증이 아니다. 실제 Guardrail 검증은 M6이다.
import { expect, test } from "@playwright/test";
import { testids } from "../src/lib/testids";
import type { ConversationView } from "../src/lib/types";
import { loginAs, switchTo, probe, ORIGIN } from "./support";
test("조회, 승인함, 단일 발송과 사용자 격리", async ({ page }) => {
  await loginAs(page, "demo-platform-g3");
  const query = "INC-2026-012 장애와 관련 티켓을 조회해 주세요";
  await page.getByTestId(testids.composerInput).fill(query);
  await page.getByTestId(testids.composerSubmit).click();
  await expect(page.getByTestId(testids.turnAnswer)).toBeVisible({ timeout: 15_000 });
  await expect(page.getByTestId(testids.turnCitedDoc).first()).toBeVisible({ timeout: 15_000 });
  const id = new URL(page.url()).pathname.split("/").at(-1)!;
  await page.getByTestId(testids.composerInput).fill("방금 내용을 팀 채널에 공유해줘");
  await page.getByTestId(testids.composerSubmit).click();
  await expect(page.getByTestId(testids.approvalCard)).toBeVisible({ timeout: 15_000 });
  await expect(page.getByTestId(testids.approvalTarget)).toHaveText("team-platform");
  await expect(page.getByTestId(testids.composerInput)).toBeDisabled();
  const conflict = await page.request.post(`/api/conversations/${id}/turns`, { headers: { Origin: ORIGIN }, data: { request: query } });
  expect(conflict.status()).toBe(409);
  expect((await conflict.json()).code).toBe("approval_pending");
  const view: ConversationView = await (await page.request.get(`/api/conversations/${id}`)).json();
  expect(Boolean(view.turn?.turn_id && view.turn?.draft_sha256)).toBe(true);
  const approvalPath = `/api/tasks/${view.turn!.turn_id}/approval`;
  const approval = { decision: "approve", draft_sha256: view.turn!.draft_sha256 };
  await page.getByTestId(testids.navApprovals).click();
  await expect(page.getByTestId(testids.inboxRow).first()).toBeVisible({ timeout: 15_000 });
  await page.getByTestId(testids.approvalOpenConversation).first().click();
  await expect(page).toHaveURL(`${ORIGIN}/c/${id}`);
  await page.getByTestId(testids.approvalApprove).click();
  await expect(page.getByTestId(testids.approvalResult)).toContainText("처리했습니다", { timeout: 15_000 });
  expect((await probe(page.request)).slack_sent).toBe(1);
  await page.reload();
  await expect(page.getByTestId(testids.approvalResult)).toBeVisible({ timeout: 15_000 });
  expect((await probe(page.request)).slack_sent).toBe(1);
  await page.request.post(approvalPath, { headers: { Origin: ORIGIN }, data: approval });
  expect((await probe(page.request)).slack_sent).toBe(1);
  await switchTo(page, "demo-finance-g3");
  await page.getByTestId(testids.composerInput).fill(query);
  await page.getByTestId(testids.composerSubmit).click();
  await expect(page.getByTestId(testids.turnAnswer)).toContainText("찾을 수 없습니다", { timeout: 15_000 });
  await page.getByTestId(testids.navApprovals).click();
  await expect(page.getByTestId(testids.inboxEmpty)).toBeVisible({ timeout: 15_000 });
  await expect(page.getByTestId(testids.inboxRow)).toHaveCount(0);
  expect((await probe(page.request)).slack_sent).toBe(1);
  expect((await page.request.get(`/api/conversations/${id}`)).status()).toBe(404);
});
